<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;

class BackfillAutomaticDecisionFlag extends Command
{
    protected $signature = 'workflow-logs:backfill-automatic-flag {--force : Actually apply the backfill. Without this flag, only a dry-run report is printed.}';

    protected $description = 'Tag pre-existing workflow_logs rows from automatic decisions (blind/defence auto pass-fail, '
        .'threshold-recalculation corrections) with metadata.automatic=true, so the workflow history stops crediting them '
        .'to whichever officer account happened to be picked to satisfy WorkflowService\'s authorization check.';

    /**
     * Each pattern is unambiguous: this exact phrasing is only ever generated by the
     * automatic code paths (ReviewScoreService::processBlindReviewResult,
     * processOpenDefenceResultIfComplete, recalculateAllDecisions) — a human typing a
     * manual rejection/approval reason would essentially never happen to match it.
     */
    private const NOTE_PATTERNS = [
        'Blind review passed. Average score:%',
        'Blind review failed. Average score:%',
        'Defence passed automatically.%',
        'Defence failed automatically.%',
        'Corrected automatically:%',
        'Recalculated under current settings:%',
    ];

    public function handle(): int
    {
        $force = (bool) $this->option('force');

        $rows = DB::table('workflow_logs')
            ->where(function ($q) {
                foreach (self::NOTE_PATTERNS as $pattern) {
                    $q->orWhere('notes', 'like', $pattern);
                }
            })
            ->orderBy('created_at')
            ->get()
            // Skip rows that already carry the flag — fresh entries created after this
            // session's fix already have it set at creation time.
            ->reject(fn ($r) => ($r->metadata ? (json_decode($r->metadata, true)['automatic'] ?? false) : false))
            ->values();

        if ($rows->isEmpty()) {
            $this->info('No pre-existing automatic-decision log entries need backfilling.');

            return self::SUCCESS;
        }

        $this->info("Found {$rows->count()} log entr".($rows->count() === 1 ? 'y' : 'ies').' to backfill:');
        $this->table(
            ['Proposal', 'Action', 'Occurred'],
            $rows->map(fn ($r) => [
                DB::table('proposals')->where('id', $r->proposal_id)->value('tracker_number') ?? $r->proposal_id,
                $r->action,
                $r->created_at,
            ])
        );

        if (! $force) {
            $this->comment('This was a DRY RUN — nothing was changed. Re-run with --force to apply.');

            return self::SUCCESS;
        }

        foreach ($rows as $row) {
            $metadata = $row->metadata ? json_decode($row->metadata, true) : [];
            $metadata['automatic'] = true;

            DB::table('workflow_logs')
                ->where('id', $row->id)
                ->update(['metadata' => json_encode($metadata)]);
        }

        $this->info("Backfilled {$rows->count()} log entr".($rows->count() === 1 ? 'y' : 'ies').'.');

        return self::SUCCESS;
    }
}
